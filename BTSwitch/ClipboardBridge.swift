import AppKit

/// Reads and writes the system clipboard (text only). Main thread only.
enum ClipboardBridge {
    /// Markers apps set on clipboard items that shouldn't leave the Mac:
    /// passwords from password managers, and short-lived content.
    /// See nspasteboard.org.
    private static let privateTypes: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]

    enum ReadResult {
        case text(String)
        case skipped(String)   // reason, for the log
    }

    static func readForSending() -> ReadResult {
        dispatchPrecondition(condition: .onQueue(.main))
        let pb = NSPasteboard.general
        let types = pb.types ?? []
        if types.contains(where: privateTypes.contains) {
            return .skipped("the clipboard holds a password or private item")
        }
        guard let text = pb.string(forType: .string), !text.isEmpty else {
            return .skipped("the clipboard has no text")
        }
        guard Clipboard.command(for: text) != nil else {
            return .skipped("the clipboard text is larger than \(BTProtocol.maxClipboardBytes / 1024) KB")
        }
        return .text(text)
    }

    static func write(_ text: String, from source: String) {
        dispatchPrecondition(condition: .onQueue(.main))
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(text, forType: .string)
    }
}
